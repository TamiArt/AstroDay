export function NatalPlanetStory({ planet }: { planet: NatalPlanetPersonalizedAnalysis }) {
  if (!planet.available) {
    return <p className="text-sm leading-relaxed text-gray-600">{planet.interpretation} Персональные выводы не подменяются предположениями.</p>;
  }

  const name = PLANET_NAMES[planet.planet] ?? planet.name;
  const meaning = PLANET_MEANINGS[planet.planet] ?? 'свою символическую функцию';
  const houseName = planet.house ? HOUSE_NAMES[planet.house] : null;
  const ruled = planet.ruledHouses.map((house) => `${house}-й дом — ${HOUSE_NAMES[house] ?? 'сфера не определена'}`);
  const signStyle = planet.sign ? SIGN_STYLES[planet.sign] : null;
  const dignityKind = planet.dignity?.dignity;
  const mercuryInVirgo = planet.planet === 'Mercury' && planet.sign === 'Дева';
  const mercuryInOwnSign = planet.planet === 'Mercury' && ['Близнецы', 'Дева'].includes(planet.sign ?? '');
  const formsBhadra = mercuryInOwnSign && [1, 4, 7, 10].includes(planet.house ?? 0);
  const dignityText = mercuryInVirgo
    ? 'Дева — собственный знак Меркурия и знак его экзальтации. В традиции Джйотиш оба достоинства учитываются одновременно; это не означает, что остальные показатели карты можно не учитывать.'
    : dignityKind === 'exalted'
      ? 'В традиции Джйотиш это положение называют экзальтацией: качества планеты считаются особенно выраженными.'
      : dignityKind === 'own'
        ? 'Планета находится в собственном знаке — знаке, которым она управляет.'
        : dignityKind === 'debilitated'
          ? 'Это положение называют падением. Его рассматривают как один из факторов карты, а не как приговор или характеристику личности.'
          : 'Особое достоинство по используемой модели не отмечено или не определено.';
  const applications = PLANET_APPLICATIONS[planet.planet] ?? [];
  const watchout = PLANET_WATCHOUTS[planet.planet];

  return (
    <div className="space-y-4 text-sm leading-relaxed">
      <p className="font-semibold text-gray-900">
        {planet.planet === 'Mercury' && formsBhadra
          ? mercuryInVirgo
            ? `Меркурий в ${planet.house}-м доме, в Деве, в собственном знаке и знаке экзальтации формирует Бхадра-махапуруша-йогу (Bhadra Mahapurusha Yoga).`
            : `Меркурий в ${planet.house}-м доме, в Близнецах, в собственном знаке формирует Бхадра-махапуруша-йогу (Bhadra Mahapurusha Yoga).`
          : `${name} находится в ${planet.sign ?? 'неопределённом знаке'}${planet.house ? `, в ${planet.house}-м доме` : ''}. Это одно из положений, через которые в традиции Джйотиш рассматривают темы вашей карты.`}
      </p>
      {planet.planet === 'Mercury' && formsBhadra && (
        <p className="text-gray-700">В вашей карте таким интеллектуальным ресурсом выступает Меркурий — планета мышления, знаний, общения и анализа.</p>
      )}

      <section>
        <h5 className="font-semibold text-indigo-900">1. {name} — за что отвечает?</h5>
        {planet.planet === 'Mercury' ? (
          <>
            <p className="mt-1 text-gray-800">В астрологии Меркурий символизирует:</p>
            <ul className="mt-1 list-disc space-y-1 pl-5 text-gray-800">
              <li>мышление — как человек воспринимает и обрабатывает информацию;</li>
              <li>обучение — как осваивает новые знания и инструменты;</li>
              <li>анализ — как замечает детали, сравнивает и ищет причины;</li>
              <li>общение — как формулирует и передаёт мысли;</li>
              <li>навыки — работу с текстами, числами, данными и информационными системами.</li>
            </ul>
          </>
        ) : (
          <p className="mt-1 text-gray-800">{name} в традиции Джйотиш символизирует {meaning}.</p>
        )}
      </section>

      <section>
        <h5 className="font-semibold text-indigo-900">2. В каком доме находится планета?</h5>
        <p className="mt-1 text-gray-800">
          {planet.house && houseName
            ? `${planet.house}-й дом связан с темой «${houseName}». Поэтому символические качества ${name} рассматриваются через эту сферу жизни.`
            : 'Дом планеты не определён в исходных данных, поэтому связать её качества с конкретной сферой пока нельзя.'}
        </p>
        {planet.house === 1 && <p className="mt-1 text-gray-700">Первый дом описывает личность, самостоятельность и то, как человек начинает действовать. Планета в этом доме становится заметной частью символического портрета.</p>}
        {planet.house === 10 && <p className="mt-1 text-gray-700">Десятый дом связан с профессией, ответственностью и видимыми результатами деятельности.</p>}
      </section>

      <section>
        <h5 className="font-semibold text-indigo-900">3. В каком знаке находится планета и почему это важно?</h5>
        <p className="mt-1 text-gray-800">
          {planet.sign ? `${name} находится в знаке ${planet.sign}.` : 'Знак планеты не определён.'}
          {signStyle ? ` В символическом прочтении этот знак связан с такими способами проявления: ${signStyle}.` : ''}
        </p>
        <p className="mt-1 text-gray-700">{dignityText}</p>
      </section>

      <section>
        <h5 className="font-semibold text-indigo-900">4. Какие сферы жизни связывает эта планета?</h5>
        <p className="mt-1 text-gray-800">
          {ruled.length
            ? `${name} управляет ${ruled.join('; ')}. Поэтому темы этих домов в традиционной модели связываются с положением планеты.`
            : 'В доступных данных управляемые этой планетой дома не определены.'}
        </p>
        {planet.planet === 'Mercury' && planet.ruledHouses.includes(10) && (
          <p className="mt-1 text-gray-700">Поскольку Меркурий управляет 10-м домом, его положение также связывается с профессиональной реализацией. В символическом прочтении интеллектуальные навыки и способы работы с информацией могут становиться частью карьерной траектории.</p>
        )}
      </section>

      {planet.planet === 'Mercury' && (
        <section className="rounded-lg border border-indigo-100 bg-white/80 p-3">
          <h5 className="font-semibold text-indigo-900">5. Бхадра-махапуруша-йога</h5>
          {formsBhadra ? (
            <>
              <p className="mt-1 text-gray-800">Меркурий находится в собственном знаке или экзальтации и занимает кендру — {planet.house}-й дом. По этим условиям формируется Бхадра-махапуруша-йога (Bhadra Mahapurusha Yoga).</p>
              <p className="mt-1 text-gray-700">В традиции Джйотиш её связывают с интеллектом, обучением, речью, аналитическими способностями и умением применять знания на практике. Полная оценка силы йоги требует также учитывать аспекты, соединения и другие условия карты.</p>
            </>
          ) : (
            <p className="mt-1 text-gray-700">Для Бхадра-махапуруша-йоги Меркурий должен находиться в собственном знаке — Близнецах или Деве — либо в экзальтации в Деве и одновременно занимать один из угловых домов: 1-й, 4-й, 7-й или 10-й. По доступным положениям все эти условия не подтверждены.</p>
          )}
        </section>
      )}

      <section>
        <h5 className="font-semibold text-indigo-900">{planet.planet === 'Mercury' ? '6. Где эти качества могут быть полезны?' : '5. Где эти качества могут быть полезны?'}</h5>
        <ul className="mt-1 list-disc space-y-1 pl-5 text-gray-800">
          {applications.map((item) => <li key={item}>{item}</li>)}
        </ul>
      </section>

      <section className="rounded-lg border border-amber-100 bg-amber-50/70 p-3">
        <h5 className="font-semibold text-amber-900">{planet.planet === 'Mercury' ? '7. Возможная обратная сторона' : '6. На что обратить внимание'}</h5>
        <p className="mt-1 text-gray-800">{watchout ?? 'Важно учитывать, что сильные стороны могут проявляться чрезмерно.'}.</p>
      </section>

      <section className="rounded-lg bg-indigo-50/70 p-3">
        <h5 className="font-semibold text-indigo-950">Главный вывод</h5>
        <p className="mt-1 text-gray-800">
          {name} в {planet.house ? `${planet.house}-м доме` : 'неопределённом доме'}{planet.sign ? ` в знаке ${planet.sign}` : ''} описывает одну из тем вашей карты через символику ${meaning}. Это возможный ресурс для самонаблюдения и развития, а не неизменное описание характера или предсказание событий.
        </p>
      </section>
    </div>
  );
}
