function dignityText(chart: NatalChart, planetName: string): string {
  const condition = evaluatePlanetCondition(chart, planetName);
  if (!condition) return '';
  if (condition.dignity === 'exalted') return 'В традиционной оценке экзальтация поддерживает более уверенное выражение этих качеств.';
  if (condition.dignity === 'own') return 'Собственный знак традиционно связывают с большей самостоятельностью проявления функций планеты.';
  if (condition.dignity === 'debilitated') return 'Положение в знаке падения в традиционной трактовке требует большей настройки и осознанности; оно не означает невозможность результата.';
  return '';
}

